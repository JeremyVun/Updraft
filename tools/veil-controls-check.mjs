// Shared controls must work before the game module loads, without starting play or audio.
import assert from 'node:assert/strict';
import { openBrowser } from './lib/browser.mjs';
import { withoutHotReload } from './lib/vite-client-stub.mjs';
const { browser, close } = await openBrowser();
const base = process.env.BASE ?? 'http://127.0.0.1:5230/';
async function choose(page, mode) {
  await page.locator('#quality').click();
  await page.locator(`#quality-menu [data-mode="${mode}"]`).click();
}
const errors = [];
try {
  const page = await browser.newPage({viewport:{width:1100,height:700}});
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    const Native = window.AudioContext;
    window.__audio = [];
    window.AudioContext = class extends Native { constructor(...args) { super(...args); window.__audio.push(this); } };
  });
  await withoutHotReload(page);
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route('**/src/main.ts*', async route => {
    await gate;
    const response = await route.fetch(), body = await response.text();
    // Expose probes without enabling shot mode's hidden controls/fixed clock.
    assert.equal((body.match(/if \(QA && params.shot\) \{/g) ?? []).length, 2);
    await route.fulfill({response,body:body.replaceAll('if (QA && params.shot) {','if (true) {')});
  });
  await page.goto(base+'?analytics=0&progress=0');
  await page.waitForFunction(() => document.querySelector('#sound').dataset.on === 'true');
  for(const selector of ['#sound','#fullscreen','#quality'])assert(await page.locator(selector).isVisible());
  assert.equal(await page.locator('#volume').isVisible(),false,'volume waits for the pointer');
  await page.locator('#sound').hover();
  assert(await page.locator('#volume').isVisible());
  await page.screenshot({path:'/tmp/updraft-veil-controls-volume.png'});
  await page.locator('#volume').fill('0.4');
  assert.equal(await page.evaluate(() => localStorage.getItem('updraft.volume.v1')),'0.4');
  assert.equal(await page.locator('#sound').getAttribute('data-level'),'low');
  await page.locator('#sound').click();
  await choose(page, 'high');
  assert.equal(await page.locator('#sound').getAttribute('data-on'),'false');
  assert.equal(await page.evaluate(() => __audio.length),0);
  assert.equal(await page.locator('#begin').isEnabled(),false);
  await page.locator('#fullscreen').click();
  await page.waitForFunction(() => !!document.fullscreenElement);
  assert(await page.locator('#veil').isVisible());
  await page.locator('#fullscreen').click();
  await page.waitForFunction(() => !document.fullscreenElement);
  await page.screenshot({path:'/tmp/updraft-veil-controls-loading.png'});
  release();
  await page.waitForSelector('#veil.ready',{timeout:90000});
  assert.equal(await page.evaluate(() => __game.quality.mode),'high');
  assert.equal(await page.evaluate(() => __game.quality.level.name),'high');
  assert.equal(await page.locator('#quality').getAttribute('data-quality'),'high');
  assert.equal(await page.evaluate(() => __audio.length),0);
  await choose(page, 'medium');
  assert.equal(await page.evaluate(() => __game.quality.level.name),'medium');
  assert.equal(await page.locator('#quality').getAttribute('data-quality'),'medium');
  await page.locator('#sound').click(); await page.locator('#sound').click();
  assert.equal(await page.evaluate(() => __audio.length),0,'ready veil must remain silent');
  assert.equal(await page.locator('#veil').evaluate(e=>e.classList.contains('departing')),false);
  await page.locator('#quality').blur();
  await page.screenshot({path:'/tmp/updraft-veil-controls-ready.png'});
  await page.locator('#begin').click();
  await page.waitForSelector('#veil',{state:'detached'});
  assert.equal(await page.locator('#sound').getAttribute('data-on'),'false','Begin respects mute');
  assert.equal(await page.evaluate(() => __audio.length),0);
  await page.locator('#sound').click();
  await page.waitForFunction(() => __audio.length===1 && __audio[0].state==='running');
  assert.equal(await page.evaluate(() => __game.sound.volume),0.4,'Begin and unmute respect the volume');
  await page.locator('#volume').focus();
  await page.keyboard.press('ArrowUp');
  assert.equal(await page.evaluate(() => __game.sound.volume),0.41,'keyboard volume reaches the engine');
  await page.keyboard.press('ArrowDown');
  await page.locator('#volume').blur();
  await page.keyboard.press('m');
  await page.waitForFunction(() => __audio[0].state==='suspended');
  await page.keyboard.press('m');
  await page.waitForFunction(() => __audio[0].state==='running');
  assert.equal(await page.evaluate(() => __game.sound.volume),0.4,'M keeps the volume');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#sound').dataset.on==='true');
  assert.equal(await page.locator('#volume').inputValue(),'0.4','reload restores the volume');
  assert.equal(await page.evaluate(() => __audio.length),0,'remembered preferences do not start audio');
  await page.close();
  const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  await withoutHotReload(phone);
  await phone.route('**/src/main.ts*',r=>r.fulfill({contentType:'application/javascript',body:'await new Promise(() => {});'}));
  await phone.goto(base+'?analytics=0&progress=0');
  await phone.waitForFunction(() => document.querySelector('#sound').dataset.on==='true');
  assert.equal(await phone.locator('#sound').isVisible(),false,'phone controls start folded');
  await phone.locator('#corner-toggle').tap();
  assert(await phone.locator('#volume').isVisible(),'touch shows the volume with the open corner');
  await phone.locator('#volume').fill('0.7');
  assert.equal(await phone.evaluate(() => localStorage.getItem('updraft.volume.v1')),'0.7');
  await phone.locator('#sound').tap();
  await choose(phone, 'low');
  assert.equal(await phone.locator('#sound').getAttribute('data-on'),'false');
  assert.equal(await phone.locator('#begin').isEnabled(),false);
  assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth),390);
  await phone.locator('#quality').blur();
  await phone.screenshot({path:'/tmp/updraft-veil-controls-phone.png'});
  assert.deepEqual(errors,[]);
  console.log('Veil controls passed: loading-time sound/volume/quality/fullscreen, silent startup, volume on Begin and reload, keyboard toggles, in-game unmute and phone touch through the folded corner.');
} finally { await close(); }
