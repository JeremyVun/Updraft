import './lib/typescript.mjs';
import assert from 'node:assert/strict';
import * as THREE from 'three';
globalThis.location = { search: '?shot' };
globalThis.window = { matchMedia: () => ({ matches: false }) };
const { SeaLife } = await import('../src/fx/sealife.ts');
const { swellUniforms, swellLift } = await import('../src/world/water/swell.ts');
const { tuning } = await import('../src/tuning.ts');
const wind = { sample(_x, _z, out) { return Object.assign(out, { x: 0, z: 0, energy: 0, lift: 0 }); } };
const sea = new SeaLife(wind, new THREE.PerspectiveCamera());
sea.surfaceWhale(new THREE.Vector3(0, 0, 0), .7);
const presence = sea.body.mesh.material.uniforms.uPresence;
assert.equal(presence.value, 0, 'no silhouette pops in on spawn');
assert.equal(sea.sleeper.mesh.material.uniforms.uPresence.value, 1, 'later whale keeps its authored visibility');
let dive = null, count = 0;
let previous = 0;
sea.onWhaleSound = kind => { if (kind === 'whale-dive') { dive = swellUniforms.uSurge.value.clone(); count++; } };
for (let i = 0; i < 30 * 60; i++) {
  sea.update(1 / 60, 100 + i / 60);
  const t = (i + 1) / 60, a = presence.value;
  if (t <= 3.5) assert(a >= previous - 1e-12 && a <= 1 + 1e-12, `gradual appearance: ${t} ${a} ${previous}`);
  if (t >= 3.5 && t <= 16) assert(Math.abs(a - 1) < 1e-12, 'surfacing remains fully visible');
  if (t >= 16) assert(a <= previous + 1e-12, 'gradual disappearance below the water');
  previous = a;
}
assert.equal(presence.value, 0, 'already invisible before the encounter is retired');
assert.equal(count, 1, 'one swell at the visible tail entering the water');
assert(dive && dive.w === tuning.opening.crossing.diveSwell);
assert.equal(swellUniforms.uSurge.value.w, dive.w, 'the inactive later whale cannot erase this swell');
const x = dive.x + 60, z = dive.y;
const near = Math.abs(swellLift(x, z, dive.z + 10));
assert(Number.isFinite(near) && near > .01, 'the shared water surface carries the dive wave');
sea.update(1 / 60, dive.z + 61);
assert.equal(swellUniforms.uSurge.value.w, 0, 'the first swell expires after crossing the passage');
swellUniforms.uSurge.value.copy(dive);
sea.sleeper.surgeAt = dive.z;
sea.sleeper.phase = 'gone'; sea.sleeper.time = 31;
sea.sleeper.update(1 / 60, 150);
assert.equal(swellUniforms.uSurge.value.w, 0, 'the later whale still clears its own finished swell');
console.log({ dive: dive.toArray(), sampledLift: near, count });
